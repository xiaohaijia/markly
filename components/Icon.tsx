import { LineIcon } from "./LineTool";
import {
  PencilSimple,
  Cursor,
  Rectangle,
  Circle,
  ArrowUpRight,
  TextT,
  ChatText,
  Eye,
  EyeSlash,
  X,
  MagnifyingGlass,
  Plus,
  DotsThree,
  ArrowCounterClockwise,
  ArrowClockwise,
  Trash,
  DownloadSimple,
  UploadSimple,
  ArrowSquareOut,
  Check,
  Note,
  TextUnderline,
  TextStrikethrough,
  Highlighter,
  SidebarSimple,
  BookOpen,
  LinkSimple,
  FloppyDisk,
} from "@phosphor-icons/react";
const icons = {
  pen: PencilSimple,
  pointer: Cursor,
  rect: Rectangle,
  ellipse: Circle,
  arrow: ArrowUpRight,
  text: TextT,
  note: ChatText,
  eye: Eye,
  hidden: EyeSlash,
  close: X,
  search: MagnifyingGlass,
  plus: Plus,
  more: DotsThree,
  undo: ArrowCounterClockwise,
  redo: ArrowClockwise,
  delete: Trash,
  download: DownloadSimple,
  upload: UploadSimple,
  external: ArrowSquareOut,
  check: Check,
  page: Note,
  underline: TextUnderline,
  strike: TextStrikethrough,
  highlight: Highlighter,
  panel: SidebarSimple,
  book: BookOpen,
  link: LinkSimple,
  save: FloppyDisk,
};
export type IconName = keyof typeof icons | "line" | "wave" | "double";
export function Icon({ name, size = 20 }: { name: IconName; size?: number }) {
  if (name === "line" || name === "wave" || name === "double")
    return <LineIcon kind={name} width={size} />;
  const Component = icons[name];
  return <Component size={size} weight="regular" aria-hidden="true" />;
}
